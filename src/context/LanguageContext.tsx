interface LanguageContextType {
  language: string;
  setLanguage: (lang: string) => void;
  timezone: string;
  setTimezone: (tz: string) => void;
  getTimezoneOffset: () => number;
  formatTimeInTimezone: (date?: Date | number) => string;
  t: (key: string) => string;
  isRtl: boolean;
  currentLangCode: string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'English',
  setLanguage: () => {},
  timezone: '(UTC-07:00)',
  setTimezone: () => {},
  getTimezoneOffset: () => -420,
  formatTimeInTimezone: () => '',
  t: (key: string) => key,
  isRtl: false,
  currentLangCode: 'en'
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<string>(() => {
    return localStorage.getItem('rajadhan_language') || 'English';
  });

  const [timezone, setTimezoneState] = useState<string>(() => {
    return localStorage.getItem('rajadhan_timezone') || '(UTC-07:00)';
  });

  // Find language object with exhaustive matching for name, code, and native names
  const currentLangObj = useMemo(() => {
    const raw = (language || '').toLowerCase().trim();
    return ALL_LANGUAGES.find(
      l => l.name.toLowerCase() === raw || 
           l.code.toLowerCase() === raw ||
           l.nativeName.toLowerCase() === raw ||
           (raw === 'हिंदी' && l.code === 'hi') ||
           (raw === 'हिन्दी' && l.code === 'hi')
    ) || ALL_LANGUAGES[0];
  }, [language]);

  const setLanguage = (newLang: string) => {
    const raw = (newLang || '').toLowerCase().trim();
    const found = ALL_LANGUAGES.find(
      l => l.name.toLowerCase() === raw || 
           l.code.toLowerCase() === raw || 
           l.nativeName.toLowerCase() === raw ||
           (raw === 'हिंदी' && l.code === 'hi') ||
           (raw === 'हिन्दी' && l.code === 'hi')
    );
    const targetName = found ? found.name : newLang;
    setLanguageState(targetName);
    localStorage.setItem('rajadhan_language', targetName);
    if (found) {
      localStorage.setItem('rajadhan_language_code', found.code);
    }
  };

  const setTimezone = (newTz: string) => {
    setTimezoneState(newTz);
    localStorage.setItem('rajadhan_timezone', newTz);
  };

  const isRtl = ['ar', 'fa', 'ur'].includes(currentLangObj.code);

  useEffect(() => {
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    document.documentElement.lang = currentLangObj.code;
    
    // Save to Firestore user profile if logged in
    const uid = localStorage.getItem('user_uid');
    if (uid) {
      import('../firebase').then(({ db }) => {
        if (db) {
          import('firebase/firestore').then(({ doc, updateDoc }) => {
            updateDoc(doc(db, 'users', uid), {
              language: currentLangObj.name,
              languageCode: currentLangObj.code,
              updatedAt: Date.now()
            }).catch(() => {});
          });
        }
      }).catch(() => {});
    }
  }, [currentLangObj, isRtl]);

  // Sync across tabs
  useEffect(() => {
    const handleStorage = (e: StorageEvent) => {
      if (e.key === 'rajadhan_language' && e.newValue) {
        setLanguageState(e.newValue);
      }
    };
    window.addEventListener('storage', handleStorage);
    return () => window.removeEventListener('storage', handleStorage);
  }, []);

  const t = (key: string): string => {
    const code = currentLangObj.code;
    if (COMMON_TRANSLATIONS[code] && COMMON_TRANSLATIONS[code][key]) {
      return COMMON_TRANSLATIONS[code][key];
    }
    if (TRANSLATIONS[code] && TRANSLATIONS[code][key]) {
      return TRANSLATIONS[code][key];
    }
    if (ADDITIONAL_TRANSLATIONS[code] && ADDITIONAL_TRANSLATIONS[code][key]) {
      return ADDITIONAL_TRANSLATIONS[code][key];
    }
    if (COMMON_TRANSLATIONS.en && COMMON_TRANSLATIONS.en[key]) {
      return COMMON_TRANSLATIONS.en[key];
    }
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return key;
  };

  const getTimezoneOffset = (): number => {
    const tzItem = QUOTEX_TIMEZONES.find(t => timezone.includes(t.value));
    return tzItem ? tzItem.offsetMinutes : -420;
  };

  const formatTimeInTimezone = (dateInput?: Date | number): string => {
    const d = dateInput ? (typeof dateInput === 'number' ? new Date(dateInput) : dateInput) : new Date();
    const targetOffset = getTimezoneOffset();
    const utcMs = d.getTime() + (d.getTimezoneOffset() * 60000);
    const targetDate = new Date(utcMs + (targetOffset * 60000));
    
    return targetDate.toLocaleTimeString('en-GB', {
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: false
    });
  };

  return (
    <LanguageContext.Provider value={{
      language,
      setLanguage,
      timezone,
      setTimezone,
      getTimezoneOffset,
      formatTimeInTimezone,
      t,
      isRtl,
      currentLangCode: currentLangObj.code
    }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
